import express from "express";
import { createExpressMiddleware } from "@trpc/server/adapters/express";
import { appRouter } from "../routers";
import { createContext } from "./context";
import { registerOwnerPasswordAuthRoutes } from "./ownerAuth";
import { registerStorageProxy } from "./storageProxy";

/**
 * Shared Express application for the local server and Vercel's serverless handler.
 * Static frontend serving remains runtime-specific; API paths stay identical.
 */
export function createApp() {
  const app = express();
  app.use(express.json({ limit: "50mb" }));
  app.use(express.urlencoded({ limit: "50mb", extended: true }));
  registerStorageProxy(app);
  registerOwnerPasswordAuthRoutes(app);
  app.use(
    "/api/trpc",
    createExpressMiddleware({
      router: appRouter,
      createContext,
    }),
  );
  return app;
}
